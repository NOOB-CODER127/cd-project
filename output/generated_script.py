def score_docking(mol: MoleculeRecord, target_key: str, exhaustiveness: int = 8) -> float:
    tgt = TARGETS[target_key]
    residues = tgt.get('pocket_residues', [])
    d_g = -3.5 - 0.35 * min(5.0, max(0.5, mol.props.get('LogP', 2.0)))
    d_g -= 1.15 * min(mol.props.get('AromaticRings', 0), len(residues) * 0.4)
    d_g -= 0.85 * min(mol.props.get('HBD', 0) + mol.props.get('HBA', 0), len(residues) * 0.6)
    d_g += 0.28 * min(12, mol.props.get('RotatableBonds', 0))
    seed = f'{mol.smiles}:{target_key}:{exhaustiveness}'
    h_val = int(hashlib.md5(seed.encode()).hexdigest()[:6], 16)
    d_g += ((h_val % 1000) / 1000.0 - 0.5) * 0.8 - 0.15 * math.log(max(1, exhaustiveness))
    return round(d_g, 2)

